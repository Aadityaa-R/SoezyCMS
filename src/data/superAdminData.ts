export function loadSuperAdminState(): SuperAdminState {
  if (typeof window === 'undefined') {
    return {
      clinics: INITIAL_CLINICS,
      admins: INITIAL_ADMIN_ASSIGNMENTS,
      agreements: INITIAL_AGREEMENTS,
      facilities: INITIAL_FACILITY_CATALOGUE,
      onboarding: INITIAL_ONBOARDING_CHECKLISTS,
      auditLogs: INITIAL_AUDIT_LOGS,
      alerts: INITIAL_ALERTS,
      announcements: INITIAL_ANNOUNCEMENTS,
      settings: INITIAL_SETTINGS,
    };
  }

  try {
    const raw = localStorage.getItem(SUPER_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      const loadedClinics = (parsed.clinics || INITIAL_CLINICS).map((c: ClinicAdministrativeProfile) => {
        const classifications = getClinicClassifications(c);
        return {
          ...c,
          facilityClassifications: classifications,
          optedFacilities: classifications,
          entitledFacilities: classifications,
          enabledModules: c.status === 'active' ? calculateModulesForClassifications(classifications) : (c.enabledModules || []),
        };
      });

      return {
        clinics: loadedClinics,
        admins: parsed.admins || INITIAL_ADMIN_ASSIGNMENTS,
        agreements: parsed.agreements || INITIAL_AGREEMENTS,
        facilities: parsed.facilities || INITIAL_FACILITY_CATALOGUE,
        onboarding: parsed.onboarding || INITIAL_ONBOARDING_CHECKLISTS,
        auditLogs: parsed.auditLogs || INITIAL_AUDIT_LOGS,
        alerts: parsed.alerts || INITIAL_ALERTS,
        announcements: parsed.announcements || INITIAL_ANNOUNCEMENTS,
        settings: parsed.settings || INITIAL_SETTINGS,
      };
    }
  } catch {}

  return {
    clinics: INITIAL_CLINICS,
    admins: INITIAL_ADMIN_ASSIGNMENTS,
    agreements: INITIAL_AGREEMENTS,
    facilities: INITIAL_FACILITY_CATALOGUE,
    onboarding: INITIAL_ONBOARDING_CHECKLISTS,
    auditLogs: INITIAL_AUDIT_LOGS,
    alerts: INITIAL_ALERTS,
    announcements: INITIAL_ANNOUNCEMENTS,
    settings: INITIAL_SETTINGS,
  };
}

export function saveSuperAdminState(state: SuperAdminState): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(SUPER_STORAGE_KEY, JSON.stringify(state));
  } catch {}
}
